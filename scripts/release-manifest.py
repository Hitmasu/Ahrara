#!/usr/bin/env python3
"""Create the signed static update manifest from already-built release binaries.

Requires Python 3.11+ and OpenSSL 3. The private release key never enters a build
or an artifact. Run --help for the publishing contract.
"""
import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import tomllib

CONTEXT = b"ahrara-release-v1\0"
TARGETS = [f"{system}-{arch}" for system in ("linux", "darwin", "windows")
           for arch in ("x86_64", "aarch64")]
CHANNELS = ("brew", "npm")


def homebrew_formula(version, artifacts):
    """Fill only release metadata; keep the checked-in install/test implementation."""
    template = (Path(__file__).resolve().parent.parent / "Formula" / "ahrara.rb").read_text()
    begin = "  # BEGIN RELEASE METADATA (generated by scripts/release-manifest.py)\n"
    end = "  # END RELEASE METADATA\n"
    before, metadata = template.split(begin)
    _, after = metadata.split(end)
    lines = [f'  version "{version}"', ""]
    for system, condition in (("darwin", "macos"), ("linux", "linux")):
        lines.append(f"  on_{condition} do")
        for arch, cpu in (("aarch64", "arm"), ("x86_64", "intel")):
            artifact = artifacts[f"{system}-{arch}"]
            lines.extend([
                f"    on_{cpu} do",
                f'      url "{artifact["url"]}", using: :nounzip',
                f'      sha256 "{artifact["sha256"]}"',
                "    end",
            ])
        lines.extend(["  end", ""])
    return before + begin + "\n".join(lines) + end + after


def openssl(*args):
    return subprocess.run(["openssl", *map(str, args)], check=True,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE).stdout


def generate(args):
    version = args.version
    if not re.fullmatch(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", version):
        raise ValueError("release version must be stable SemVer, without a v prefix")
    crate = Path(__file__).resolve().parent.parent / "src" / "cli" / "Cargo.toml"
    if version != tomllib.loads(crate.read_text())["package"]["version"]:
        raise ValueError("release version must match src/cli/Cargo.toml")
    # The DER prefix identifies an Ed25519 public key, followed by its 32 raw bytes.
    public_der = openssl("pkey", "-in", args.key, "-pubout", "-outform", "DER")
    prefix = bytes.fromhex("302a300506032b6570032100")
    if len(public_der) != len(prefix) + 32 or not public_der.startswith(prefix):
        raise ValueError("release signing key must be Ed25519")
    if public_der[len(prefix):].hex() != args.public_key.lower():
        raise ValueError("signing key does not match the public key embedded in release builds")
    with tempfile.TemporaryDirectory(prefix="ahrara-release-") as work:
        work = Path(work)
        message_file, signature_file = work / "message", work / "signature"
        channels = {}
        if args.previous:
            previous_bytes = args.previous.read_bytes()
            if len(previous_bytes) > 128 * 1024:
                raise ValueError("previous manifest is too large")
            previous = json.loads(previous_bytes)
            payload = base64.b64decode(previous["payload"], validate=True)
            message_file.write_bytes(CONTEXT + payload)
            signature_file.write_bytes(base64.b64decode(previous["signature"], validate=True))
            public_file = work / "public.der"
            public_file.write_bytes(public_der)
            openssl("pkeyutl", "-verify", "-pubin", "-inkey", public_file,
                    "-keyform", "DER", "-rawin", "-in", message_file,
                    "-sigfile", signature_file)
            previous = json.loads(payload)
            if previous["schema_version"] != 1:
                raise ValueError("unsupported previous manifest")
            channels = previous["channels"]
            old_version = channels.get("direct", {}).get("version", "0.0.0")
            if tuple(map(int, version.split('.'))) < tuple(map(int, old_version.split('.'))):
                raise ValueError("cannot publish an older direct release")
        artifacts = {}
        for target in TARGETS:
            name = f"ahrara-{target}" + (".exe" if target.startswith("windows-") else "")
            artifact = args.assets / name
            size = artifact.stat().st_size
            if not 0 < size <= 256 * 1024 * 1024:
                raise ValueError(f"invalid artifact size: {name}")
            with artifact.open("rb") as source:
                digest = hashlib.file_digest(source, "sha256").hexdigest()
            artifacts[target] = {
                "url": f"https://github.com/Hitmasu/Ahrara/releases/download/v{version}/{name}",
                "sha256": digest, "size": size,
            }
        release = {"version": version, "artifacts": artifacts}
        if channels.get("direct", {}).get("version") == version and channels["direct"] != release:
            raise ValueError("published version is immutable; changed binaries require a new version")
        channels["direct"] = release
        formula = homebrew_formula(version, artifacts) if args.homebrew_output else None
        # Native packages may support only a subset of platforms. Publication must
        # explicitly acknowledge each available channel/platform; never assume parity.
        for availability in args.available:
            channel, target = availability.split("=", 1)
            if channel not in CHANNELS or target not in TARGETS:
                raise ValueError("--available must be channel=platform, e.g. brew=darwin-aarch64")
            if channels.get(channel, {}).get("version") != version:
                channels[channel] = {"version": version, "artifacts": {}}
            channels[channel]["artifacts"][target] = artifacts[target]
        payload = json.dumps({"schema_version": 1, "channels": channels},
                             separators=(",", ":"), sort_keys=True).encode()
        message_file.write_bytes(CONTEXT + payload)
        signature = openssl("pkeyutl", "-sign", "-inkey", args.key, "-rawin", "-in", message_file)
        envelope = {"payload": base64.b64encode(payload).decode(),
                    "signature": base64.b64encode(signature).decode()}
        args.output.parent.mkdir(parents=True, exist_ok=True)
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(mode="w", dir=args.output.parent, delete=False) as file:
                temporary = Path(file.name)
                json.dump(envelope, file, indent=2)
                file.write("\n")
                file.flush()
                os.fsync(file.fileno())
            os.chmod(temporary, 0o644)
            os.replace(temporary, args.output)
        finally:
            if temporary and temporary.exists():
                temporary.unlink()
    if formula is not None:
        args.homebrew_output.parent.mkdir(parents=True, exist_ok=True)
        args.homebrew_output.write_text(formula)
        print(f"Homebrew formula generated: {args.homebrew_output}")
    if getattr(args, "plugin_key_output", None):
        args.plugin_key_output.parent.mkdir(parents=True, exist_ok=True)
        args.plugin_key_output.write_text(json.dumps({"ed25519": args.public_key.lower()}, indent=2) + "\n")
        print(f"Plugin verification key generated: {args.plugin_key_output}")
    print(f"Signed release manifest generated: {args.output}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True)
    parser.add_argument("--assets", type=Path, required=True)
    parser.add_argument("--key", type=Path, required=True, help="private Ed25519 PEM key, kept outside the repository")
    parser.add_argument("--public-key", required=True, help="64 hex characters embedded as AHRARA_UPDATE_PUBLIC_KEY")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--homebrew-output", type=Path, help="also generate Formula/ahrara.rb from the same binary checksums")
    parser.add_argument("--plugin-key-output", type=Path, help="also generate src/plugin/release-key.json for review and commit")
    parser.add_argument("--previous", type=Path, help="previous signed manifest, preserving channel availability")
    parser.add_argument("--available", action="append", default=[], help="already-published channel=platform; repeat as needed")
    args = parser.parse_args()
    try:
        generate(args)
    except (ValueError, OSError, KeyError, subprocess.CalledProcessError) as error:
        # OpenSSL diagnostics are deliberately not echoed; the key stays private.
        parser.exit(1, f"Release manifest failed: {type(error).__name__}: "
                       f"{str(error) if not isinstance(error, subprocess.CalledProcessError) else 'OpenSSL signing/verification failed'}\n")


if __name__ == "__main__":
    main()
