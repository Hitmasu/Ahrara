pub static LANGUAGES: [&Strings; 3] = [&EN, &PT_BR, &ES];

/// The saved preference, else the first supported language the browser asks
/// for by weight, else English.
pub fn negotiate(preference: Option<&str>, accept_language: Option<&str>) -> &'static Strings {
    preference
        .and_then(find)
        .or_else(|| {
            let mut tags: Vec<(f32, &str)> = accept_language?
                .split(',')
                .filter_map(|item| {
                    let mut parts = item.split(';');
                    let tag = parts.next()?.trim();
                    let weight = match parts.find_map(|p| p.trim().strip_prefix("q=")) {
                        Some(weight) => weight.parse().ok()?,
                        None => 1.0,
                    };
                    Some((weight, tag))
                })
                .collect();
            tags.sort_by(|a, b| b.0.total_cmp(&a.0));
            tags.into_iter()
                .filter(|(weight, _)| *weight > 0.0)
                .find_map(|(_, tag)| find(tag))
        })
        .unwrap_or(&EN)
}

// Any regional variant selects the language: pt-PT reads the Brazilian text.
pub(crate) fn find(tag: &str) -> Option<&'static Strings> {
    let primary = tag.split(['-', '_']).next()?;
    LANGUAGES.into_iter().find(|strings| {
        strings
            .code
            .split('-')
            .next()
            .is_some_and(|code| code.eq_ignore_ascii_case(primary))
    })
}

impl Strings {
    /// app.js's messages, for the page's `data-strings` attribute.
    pub fn script(&self) -> String {
        serde_json::json!({
            "copied": self.address_copied,
            "clipboard": self.clipboard_unavailable,
            "refreshFailed": self.refresh_failed,
            "newEmail": self.new_email,
            "historyChanged": self.history_changed,
            "settingsChanged": self.settings_changed,
            "connected": self.connected,
            "disconnected": self.disconnected,
            "imagesAllowed": self.images_allowed,
            "persistent": self.persistent,
            "bestEffort": self.best_effort,
        })
        .to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn preference_then_weighted_browser_languages_then_english() {
        assert_eq!(negotiate(Some("es"), Some("pt-BR")).code, "es");
        assert_eq!(negotiate(None, Some("pt-PT,pt;q=0.9")).code, "pt-BR");
        assert_eq!(negotiate(None, Some("de, en;q=0.5, es;q=0.8")).code, "es");
        assert_eq!(negotiate(None, Some("es;q=0, fr")).code, "en");
        assert_eq!(negotiate(Some("klingon"), None).code, "en");
    }
}
